"""Write the suite map: ``map.json`` (everything) plus Markdown for people to read."""

from __future__ import annotations

from pathlib import Path

from ticket2test.models.suite_map import AreaSummary, Count, KeyValues, SuiteMap


def write_map(suite_map: SuiteMap, folder: Path, max_coverage: int) -> list[Path]:
    """Write the map into ``folder``; area files of areas that no longer exist are removed."""
    areas_dir = folder / "areas"
    areas_dir.mkdir(parents=True, exist_ok=True)
    written = [folder / "map.json", folder / "overview.md", folder / "coverage.md"]
    written[0].write_text(suite_map.model_dump_json(indent=2), encoding="utf-8")
    written[1].write_text(render_overview(suite_map), encoding="utf-8")
    written[2].write_text(render_coverage(suite_map, max_coverage), encoding="utf-8")
    keep = set()
    for area in suite_map.areas:
        path = areas_dir / f"{_safe(area.name)}.md"
        path.write_text(render_area(area) + render_values(area), encoding="utf-8")
        keep.add(path.name)
        written.append(path)
    for old in areas_dir.glob("*.md"):
        if old.name not in keep:
            old.unlink()
    return written


def render_values(a: AreaSummary) -> str:
    """The area's known data values (kept out of render_area, which the guide prompts use)."""
    if not a.data_values:
        return ""
    lines = [
        "",
        "## Known data values",
        "",
        "Key path (entries that have it, distinct values):",
        "",
    ]
    lines += [_value_line(v) for v in a.data_values]
    return "\n".join(lines) + "\n"


def _value_line(v: KeyValues) -> str:
    head = f"- `{v.key}` ({v.entries} entries, {v.distinct} distinct"
    head += f", {v.long_text} long text)" if v.long_text else ")"
    if v.free_text:
        return f"{head}: free text (nearly every value differs)"
    shown = ", ".join(f"`{c.name}` ({c.count})" for c in v.values)
    more = v.distinct - len(v.values)
    return f"{head}: {shown}" + (f", +{more} more" if more > 0 else "")


def load_map(folder: Path) -> SuiteMap | None:
    path = folder / "map.json"
    try:
        return SuiteMap.model_validate_json(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def render_overview(m: SuiteMap) -> str:
    o = m.overview
    lines = [
        "# Suite map: overview",
        "",
        f"Built {m.built_at:%Y-%m-%d %H:%M UTC} from `{m.repo_root}`"
        + (f" at commit `{m.commit[:12]}`" if m.commit else "")
        + ". Generated by code from the index; no LLM involved.",
        "",
        f"- Tests: {o.tests} functions, {o.test_ids} pytest ids, {o.test_classes} classes",
        f"- Data entries: {o.data_entries}",
        f"- Areas: {len(m.areas)}"
        + (
            f" (changed since the last map: {', '.join(m.changed_areas) or 'none'})"
            if m.changed_areas is not None
            else ""
        ),
        f"- Chain roots: {', '.join(o.chain_roots) or 'none'}",
        "",
        "## Areas",
        "",
        "| Area | Tests | Ids | Classes | Main shapes | Data entries |",
        "|---|---|---|---|---|---|",
    ]
    for a in m.areas:
        shapes = ", ".join(f"{s.name} ({s.count})" for s in a.shapes[:3])
        lines.append(
            f"| [{a.name}](areas/{_safe(a.name)}.md) | {a.tests} | {a.test_ids} | "
            f"{len(a.classes)} | {shapes} | {a.data_entries} |"
        )
    lines += ["", "## Base classes of test classes", "", *_counts(o.base_classes, "test classes")]
    lines += ["", "## Page areas (first step below a root)", "", *_counts(o.page_areas, "tests")]
    lines += ["", "## Helpers shared by several areas", "", *_counts(o.shared_helpers, "areas")]
    lines += ["", "## Marker values seen", ""]
    lines += [f"- {k}: {', '.join(v) or '(no values)'}" for k, v in o.marker_values.items()]
    if o.unassigned_tests:
        lines += ["", f"## Tests outside every area ({len(o.unassigned_tests)})", ""]
        lines += [f"- `{t}`" for t in o.unassigned_tests[:50]]
    if o.skipped_files:
        lines += ["", f"## Files left out ({len(o.skipped_files)})", ""]
        lines += [f"- {f}" for f in o.skipped_files[:50]]
    gaps = len(m.coverage)
    lines += ["", f"Coverage: {gaps} unreferenced test-side item(s); see [coverage](coverage.md)."]
    return "\n".join(lines) + "\n"


def render_area(a: AreaSummary) -> str:
    lines = [
        f"# Area: {a.name}",
        "",
        f"Folders: {', '.join(f'`{f}`' for f in a.folders)}. "
        f"{a.tests} test functions ({a.parametrized} parametrized), {a.test_ids} pytest ids, "
        f"{a.data_entries} data entries, {a.skipped} skipped. Source digest `{a.digest[:12]}`.",
        "",
        "## Test classes",
        "",
    ]
    for c in a.classes:
        lines.append(f"### `{c.name}` ({c.tests} tests, `{c.file_path}`)")
        lines.append("")
        lines.append(f"- Bases: {', '.join(f'`{b}`' for b in c.bases) or 'none'}")
        lines.append(f"- Decorators: {', '.join(f'`@{d}`' for d in c.decorators) or 'none'}")
        if c.setup_calls:
            lines.append(f"- Setup: {'; '.join(f'`{s}`' for s in c.setup_calls)}")
        lines.append("")
    sections: list[tuple[str, list[Count], str]] = [
        ("Test shapes (kind, action)", a.shapes, "tests"),
        ("Markers", a.markers, "tests"),
        ("Page-object chains", a.chains, "tests"),
        ("Page-object actions called", a.page_actions, "tests"),
        ("Base-class helpers called", a.base_helpers, "tests"),
        ("Other repo functions called (decorators included)", a.functions, "tests"),
        ("Assertions", a.assertions, "tests"),
        ("Fixtures", a.fixtures, "tests"),
        ("Data entry keys", a.data_keys, "entries"),
        ("Expectations", a.expectations, "entries"),
        ("Placeholders in data", a.placeholders, "entries"),
    ]
    for title, counts, unit in sections:
        if not counts:
            continue
        rows = _counts(counts, unit)
        if counts is a.data_keys:
            rows = [
                f"{row} ({a.data_key_roles.get(c.name, '?')})"
                for row, c in zip(rows, counts, strict=True)
            ]
        lines += [f"## {title}", "", *rows, ""]
    lines += ["## Typical tests (one per shape)", ""]
    lines += [f"- `{e}`" for e in a.examples] or ["- none"]
    lines += ["", "## Built from", ""]
    lines += [f"- `{p}` `{h[:12]}`" for p, h in a.sources.items()]
    return "\n".join(lines) + "\n"


def render_coverage(m: SuiteMap, limit: int) -> str:
    lines = [
        "# Suite map: coverage",
        "",
        "Test-side code that nothing in the repo references: page objects and their members, "
        "helpers of the test classes' base classes, and functions in modules that test files "
        "import. Product code is not listed. Unused is not wrong: it is what the map can't "
        "describe from usage, and possibly dead code.",
        "",
    ]
    if not m.coverage:
        return "\n".join([*lines, "Nothing found."]) + "\n"
    by_kind: dict[str, list[str]] = {}
    for gap in m.coverage:
        by_kind.setdefault(gap.kind, []).append(f"- `{gap.name}` (`{gap.file_path}`)")
    shown = 0
    for kind, rows in by_kind.items():
        lines += [f"## {kind} ({len(rows)})", ""]
        room = max(0, limit - shown)
        lines += rows[:room]
        if len(rows) > room:
            lines.append(f"- ... and {len(rows) - room} more (see map.json)")
        shown += min(len(rows), room)
        lines.append("")
    return "\n".join(lines)


def _counts(counts: list[Count], unit: str) -> list[str]:
    return [f"- `{c.name}`: {c.count} {unit}" for c in counts] or ["- none"]


def _safe(name: str) -> str:
    return "".join(ch if ch.isalnum() or ch in "-_." else "_" for ch in name)
